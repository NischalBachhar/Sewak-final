const {chooseRegistrationRole}=require('./signup-helpers.cjs');
const { test, expect } = require('./test.cjs');
const { seed, db } = require('./seed.cjs');
const combined = 'Caregiver & Household Staffing Agency';
test.beforeAll(seed);

for (const width of [320, 1440]) test(`combined organization selects both service categories and persists through admin approval at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 });
  await page.goto('/auth?mode=register&role=user');
  const email = `combined-${width}-${Date.now()}@example.test`, name = `Combined Organization ${width}`;
  await page.getByLabel('Full name').fill('Combined Owner');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill('Local-test-only-123!');
  await chooseRegistrationRole(page, /Register an organization/);
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Organization/Company Name').fill(name);
  const type = page.getByRole('combobox', { name: 'Organization Type *', exact: true });
  expect(await type.locator('option').allTextContents()).toEqual(['Select organization type', 'Caregiver Agency', 'Home Care Service Provider', 'Household Staffing Agency', combined, 'Nursing / Home Healthcare Provider', 'Other']);
  await type.selectOption(combined);
  await page.getByLabel('Phone Number *').fill('9800000000');
  await page.getByRole('combobox', { name: 'City *', exact: true }).selectOption('Other');
  await page.getByLabel('Enter your city *').fill('Hetauda');
  await page.getByLabel('Address *', { exact: true }).fill('Synthetic street 12');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.getByLabel('Elderly Care', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Housekeeping', { exact: true })).toBeVisible();
  await expect(page.locator('.service-selector input:checked')).toHaveCount(0);
  await expect(page.getByRole('group', { name: 'Caregiver Support', exact: true })).toBeVisible();
  await expect(page.getByRole('group', { name: 'Household Support', exact: true })).toBeVisible();
  await page.getByLabel('Elderly Care', { exact: true }).check();
  await page.getByLabel('Personal Care Assistance', { exact: true }).check();
  await page.getByRole('combobox', { name: 'Service category', exact: true }).selectOption('household');
  await expect(page.getByLabel('Elderly Care', { exact: true })).toHaveCount(0);
  await page.getByLabel('Housekeeping', { exact: true }).check();
  await page.getByLabel('Cooking / Meal Preparation', { exact: true }).check();
  await page.getByRole('combobox', { name: 'Service category', exact: true }).selectOption('');
  await expect(page.locator('.service-selector input:checked')).toHaveCount(4);
  await page.getByRole('button', { name: 'Remove Personal Care Assistance', exact: true }).click();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(type).toHaveValue(combined);
  await type.selectOption('Household Staffing Agency');
  await type.selectOption(combined);
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.locator('.service-selector input:checked')).toHaveCount(3);
  await expect(page.locator('.signup-review')).toContainText(combined);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  const submitted = page.waitForRequest(request => request.url().endsWith('/api/auth/register') && request.method() === 'POST');
  await page.getByRole('button', { name: 'Submit application', exact: true }).click();
  const services = ['catalog_elderly_care', 'catalog_housekeeping', 'catalog_cooking_meal_preparation'];
  expect((await submitted).postDataJSON()).toMatchObject({ organizationType: combined, servicesOffered: services });
  await expect(page).toHaveURL(/\/organization\/profile/);
  await page.reload();
  await expect(type).toHaveValue(combined);
  for (const label of ['Elderly Care', 'Housekeeping', 'Cooking / Meal Preparation']) await expect(page.getByLabel(label, { exact: true })).toBeChecked();
  const user = (await db.collection('users').get()).docs.find(doc => doc.data().email === email);
  expect((await db.doc('organizations/' + user.id).get()).data()).toMatchObject({ organizationType: combined, servicesOffered: services, isApproved: false });
  expect((await db.doc('organizationApplications/' + user.id).get()).data()).toMatchObject({ organizationType: combined, servicesOffered: services, status: 'pending' });
  await page.getByRole('button', { name: /Account menu for/ }).click();
  await page.getByRole('button', { name: /Logout/ }).click();
  await page.goto('/auth');
  await page.getByLabel('Email', { exact: true }).fill('e2e-admin@example.test');
  await page.getByLabel('Password', { exact: true }).fill('Local-test-only-123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/superadmin/);
  if (width < 768) await page.getByRole('combobox', { name: 'Administration section' }).selectOption('organizations');
  else await page.getByRole('button', { name: /Organizations/ }).first().click();
  const application = page.locator('article').filter({ has: page.getByText(name, { exact: true }) });
  await expect(application).toContainText(combined);
  await application.getByRole('button', { name: 'Approve application', exact: true }).click();
  await expect(application).toHaveCount(0);
  await page.getByPlaceholder('Search organizations...').fill(combined);
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  expect((await db.doc('organizations/' + user.id).get()).data()).toMatchObject({ organizationType: combined, servicesOffered: services, isApproved: true });
});
